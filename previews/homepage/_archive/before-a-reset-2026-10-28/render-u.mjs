import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {studyNavigation} from './study-navigation.mjs';
import {renderUHeroCopy} from './u-hero-copy.mjs';
const path=new URL('./t.html',import.meta.url),baseline=await readFile(path,'utf8');
const start=baseline.indexOf('<div class="i-hero-copy"><h1 id="i-title">');
if(start<0)throw new Error('Expected one current illustrated hero copy.');
const end=baseline.indexOf('</div>',start)+6,original=baseline.slice(start,end);
if(baseline.split(original).length!==2)throw new Error('Hero copy is not unique.');
const action=original.match(/<a class="i-primary"[^>]*>[\s\S]*?<\/a>/)?.[0];
const replacement=renderUHeroCopy(action);
let next=baseline.replace(original,replacement);
next=next.replace(/<!-- study-navigation:start -->[\s\S]*?<!-- study-navigation:end -->/,studyNavigation('u'));
next=next.replaceAll('Villow · T · Videos and people','Villow · U · A working blueprint');
next=next.replace('class="version-i version-r version-s version-t"','class="version-i version-r version-s version-t version-u"');
next=next.replace('href="t.html" aria-label="Villow home"','href="u.html" aria-label="Villow home"');
next=next.replace('</head>','<link rel="stylesheet" href="u-hero-copy.css"></head>');
next=next.replace(/<!-- closing-comparison:start -->[\s\S]*?<!-- closing-comparison:end -->/,'<!-- closing-comparison:start --><a class="hc-comparison" href="t.html">Compare previous introduction · T</a><!-- closing-comparison:end -->');
const mainHero=html=>html.slice(html.indexOf('<main id="main">'),html.indexOf('<section class="i-following"'));
if(mainHero(next).replace(replacement,original)!==mainHero(baseline))throw new Error('Hero changed beyond the copy.');
const following=html=>html.slice(html.indexOf('<section class="i-following"'),html.indexOf('<footer class="i-preview-note'));
if(following(next)!==following(baseline))throw new Error('A lower section changed.');
await writeFile(new URL('./u.html',import.meta.url),next);
if(await readFile(path,'utf8')!==baseline)throw new Error('T baseline changed.');
console.log(`Rendered U: http://127.0.0.1:4399/u.html\nT preserved: ${createHash('sha256').update(baseline).digest('hex')}`);
