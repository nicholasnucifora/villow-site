import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {studyNavigation} from './study-navigation.mjs';
import {renderVFeed} from './v-feed.mjs';
import {renderVClosing} from './v-closing.mjs';
const path=new URL('./t.html',import.meta.url),baseline=await readFile(path,'utf8');
const section=(html,start)=>{const i=html.indexOf(start);if(i<0)throw new Error(`Missing section: ${start}`);return html.slice(i,html.indexOf('</section>',i)+10);};
const oldFeed=section(baseline,'<section class="ifs-section');
const closing=baseline.match(/<!-- homepage-closing:start -->[\s\S]*?<!-- homepage-closing:end -->/)?.[0];
const action=baseline.match(/<a class="i-primary"[^>]*>[\s\S]*?<\/a>/)?.[0];
if(!closing||!action)throw new Error('Missing closing or CTA');
const newFeed=renderVFeed(),newClosing=renderVClosing(action);
let next=baseline.replace(oldFeed,newFeed).replace(closing,newClosing);
next=next.replace(/<!-- study-navigation:start -->[\s\S]*?<!-- study-navigation:end -->/,studyNavigation('v'));
next=next.replaceAll('Villow · T · Videos and people','Villow · V · A finite selection');
next=next.replace('class="version-i version-r version-s version-t"','class="version-i version-r version-s version-t version-v"');
next=next.replace('href="t.html" aria-label="Villow home"','href="v.html" aria-label="Villow home"');
next=next.replace('src="n-feed.js"','src="v-feed.js"');
next=next.replace('</head>','<link rel="stylesheet" href="v-feed.css"><link rel="stylesheet" href="v-closing.css"></head>');
next=next.replace(/<!-- closing-comparison:start -->[\s\S]*?<!-- closing-comparison:end -->/,'<!-- closing-comparison:start --><a class="hc-comparison" href="t.html#feed-to-watch-later">Compare original stack · T</a><!-- closing-comparison:end -->');
const hero=html=>html.slice(html.indexOf('<main id="main">'),html.indexOf('<section class="i-following"'));
for(const start of ['<section class="ics-company"','<section class="rt-together"','<section class="sl-limits"','<section class="s-viewing"','<section class="t-social-intro"'])if(section(next,start)!==section(baseline,start))throw new Error(`Unexpected section change: ${start}`);
if(hero(next)!==hero(baseline))throw new Error('Original short hero changed.');
if((next.match(/data-ifs-demo/g)||[]).length!==1)throw new Error('Expected one feed demonstration.');
await writeFile(new URL('./v.html',import.meta.url),next);
if(await readFile(path,'utf8')!==baseline)throw new Error('T baseline changed.');
console.log(`Rendered V: http://127.0.0.1:4399/v.html#feed-to-watch-later\nT preserved: ${createHash('sha256').update(baseline).digest('hex')}`);
