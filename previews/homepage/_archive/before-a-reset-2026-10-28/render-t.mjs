import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {studyNavigation} from './study-navigation.mjs';
import {renderTSocialIntro} from './t-social-intro.mjs';
import {renderTSwipeCue} from './t-swipe-cue.mjs';
const path=new URL('./s.html',import.meta.url),baseline=await readFile(path,'utf8');
const section=(html,start)=>{const i=html.indexOf(start);if(i<0)throw new Error(`Missing section: ${start}`);return html.slice(i,html.indexOf('</section>',i)+10);};
let next=baseline;
const socialHook='<div class="r-social-band"><div class="i-width">';
if(next.split(socialHook).length!==2)throw new Error('Expected one social chapter');
next=next.replace(socialHook,socialHook+renderTSocialIntro());
const bridge=next.indexOf('<div class="ifs-bridge"'),feedEnd=next.lastIndexOf('</div>',bridge);
if(bridge<0||feedEnd<0)throw new Error('Missing feed cue insertion point');
const cue=`<!-- t-swipe-cue:start -->${renderTSwipeCue()}<!-- t-swipe-cue:end -->`;
next=next.slice(0,feedEnd)+cue+next.slice(feedEnd);
next=next.replace('Interactive example · Sample videos','Interactive illustration · Sample videos');
next=next.replace(/<!-- study-navigation:start -->[\s\S]*?<!-- study-navigation:end -->/,studyNavigation('t'));
next=next.replaceAll('Villow · S · A little more room','Villow · T · Videos and people');
next=next.replace('class="version-i version-r version-s"','class="version-i version-r version-s version-t"');
next=next.replace('href="s.html" aria-label="Villow home"','href="t.html" aria-label="Villow home"');
next=next.replace('</head>','<link rel="stylesheet" href="t-social-intro.css"><link rel="stylesheet" href="t-swipe-cue.css"><script type="module" src="t-swipe-cue.js"></script></head>');
next=next.replace(/<!-- closing-comparison:start -->[\s\S]*?<!-- closing-comparison:end -->/,'<!-- closing-comparison:start --><a class="hc-comparison" href="s.html#your-choices">Compare previous version · S</a><!-- closing-comparison:end -->');
const hero=html=>html.slice(html.indexOf('<main id="main">'),html.indexOf('<section class="i-following"'));
for(const start of ['<section class="ics-company"','<section class="rt-together"','<section class="hc-closing"','<section class="sl-limits"','<section class="s-viewing"'])if(section(next,start)!==section(baseline,start))throw new Error(`Unexpected section change: ${start}`);
const cleanFeed=section(next,'<section class="ifs-section').replace(cue,'').replace('Interactive illustration · Sample videos','Interactive example · Sample videos');
if(cleanFeed!==section(baseline,'<section class="ifs-section'))throw new Error('Feed changed beyond illustration label/cue');
if(hero(next)!==hero(baseline))throw new Error('Cloud cinema changed unexpectedly.');
if((next.match(/data-ifs-demo/g)||[]).length!==1)throw new Error('Expected one feed demonstration.');
await writeFile(new URL('./t.html',import.meta.url),next);
if(await readFile(path,'utf8')!==baseline)throw new Error('S baseline changed.');
console.log(`Rendered T: http://127.0.0.1:4399/t.html#watch-with-people\nS preserved: ${createHash('sha256').update(baseline).digest('hex')}`);
